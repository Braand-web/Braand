// Rebuild lib/fal-approved.generated.mjs from fal's public OpenAPI schemas.
// Only models whose required inputs can all be bounded are written.
import {writeFile} from 'node:fs/promises';
import {CANDIDATES,boundedModel} from './fal-model-candidates.mjs';
const approved=[];
for(const candidate of CANDIDATES){
 try{const response=await fetch('https://fal.ai/api/openapi/queue/openapi.json?endpoint_id='+encodeURIComponent(candidate.id),{signal:AbortSignal.timeout(20000)});
  if(!response.ok){console.log('skip',candidate.id,'schéma HTTP',response.status);continue;}
  const result=boundedModel(candidate,await response.json());if(result.skip){console.log('skip',candidate.id,result.skip);continue;}
  const {approvedAt,...model}=result.model;approved.push({...model,approvedAt:'2026-11-03T00:00:00.000Z'});console.log('ok',candidate.id);void approvedAt;
 }catch(error){console.log('skip',candidate.id,String(error).slice(0,120));}
}
if(!approved.length)throw Error('No fal model could be bounded; nothing written');
await writeFile(new URL('../lib/fal-approved.generated.mjs',import.meta.url),'// Generated by scripts/build-fal-approved.mjs from fal\'s OpenAPI schemas. Do not edit.\nexport const FAL_APPROVED_MODELS = '+JSON.stringify(approved,null,1)+';\n');
console.log('Wrote',approved.length,'bounded fal models');
